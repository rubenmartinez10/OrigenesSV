-- Hora simulada actual
CREATE FUNCTION ahora() RETURNS TIMESTAMPTZ
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN pausado THEN reloj_base ELSE reloj_base + (now() - real_base) END FROM sistema WHERE id = 1
$$;

-- Existencias disponibles (lotes con cantidad y sin vencer)
CREATE VIEW v_stock AS
SELECT l.sucursal_id, l.mp_id, SUM(l.cantidad) AS stock
FROM lotes l
WHERE l.cantidad > 0 AND l.vence > ahora()
GROUP BY l.sucursal_id, l.mp_id;

-- Insumos reservados por pedidos que aún no se preparan
CREATE VIEW v_reservado AS
SELECT p.sucursal_id, r.mp_id, SUM(r.cantidad) AS reservado
FROM pedido_reservas r
JOIN pedidos p ON p.id = r.pedido_id
WHERE NOT p.consumido AND p.estado NOT IN ('Cancelado','Rechazado')
GROUP BY p.sucursal_id, r.mp_id;
