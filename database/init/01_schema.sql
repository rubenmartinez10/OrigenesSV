-- =====================================================================
-- 1. Sistema y configuración
-- =====================================================================

-- Reloj simulado: hora_simulada = reloj_base + (hora_real - real_base); en pausa = reloj_base.
-- Solo corre mientras alguien usa la app (como el borrador).
CREATE TABLE sistema (
  id               SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  reloj_base       TIMESTAMPTZ NOT NULL,
  real_base        TIMESTAMPTZ NOT NULL DEFAULT now(),
  pausado          BOOLEAN NOT NULL DEFAULT FALSE,
  semana_aplicada  INTEGER,                 -- última semana simulada con precios de proveedores actualizados
  actualizado      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Parámetros de negocio de la franquicia (una sola fila)
CREATE TABLE configuracion (
  id                    SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  iva_pct               NUMERIC(5,2)  NOT NULL DEFAULT 13,
  semana_dias           SMALLINT      NOT NULL DEFAULT 7,
  llegada_a_tiempo_pct  SMALLINT      NOT NULL DEFAULT 65,   -- probabilidad de que una compra llegue a tiempo
  llegada_tarde_pct     SMALLINT      NOT NULL DEFAULT 25,
  llegada_antes_pct     SMALLINT      NOT NULL DEFAULT 10,
  desc_pendiente_min    SMALLINT      NOT NULL DEFAULT 10,   -- % de descuento si lo pendiente sigue en camino
  desc_pendiente_max    SMALLINT      NOT NULL DEFAULT 20,
  tendencia_top         SMALLINT      NOT NULL DEFAULT 5,    -- productos en «Tendencia»
  tendencia_dias        SMALLINT      NOT NULL DEFAULT 7,
  extra_unidad_pct      SMALLINT      NOT NULL DEFAULT 35,   -- tiempo extra por cada unidad adicional
  margen_min            SMALLINT      NOT NULL DEFAULT 15,   -- minutos de margen sobre el tiempo estimado
  vigencia_cotizacion_h SMALLINT      NOT NULL DEFAULT 72,
  por_vencer_dias       SMALLINT      NOT NULL DEFAULT 5,
  oferta_dias           SMALLINT      NOT NULL DEFAULT 3,
  oferta_max_pct        SMALLINT      NOT NULL DEFAULT 50,
  antiguedad_pct        NUMERIC(5,2)  NOT NULL DEFAULT 2,    -- aumento anual por antigüedad
  salario_minimo        NUMERIC(10,2) NOT NULL DEFAULT 408.80,
  btc_usd               NUMERIC(12,2) NOT NULL DEFAULT 100000,
  minutos_mesa          SMALLINT      NOT NULL DEFAULT 30    -- tiempo para pedir que desocupen la mesa
);

-- =====================================================================
-- 2. Organización: roles, sucursales y personal
-- =====================================================================

CREATE TABLE roles (
  id              VARCHAR(20) PRIMARY KEY,             -- mesero, cocinero, jefe, bodega, gerente, rrhh, gg, director
  nombre          VARCHAR(60)  NOT NULL UNIQUE,
  nivel           SMALLINT     NOT NULL,               -- jerarquía (1 = mesero … 6 = director)
  alcance         VARCHAR(12)  NOT NULL CHECK (alcance IN ('sucursal','franquicia')),
  pantalla_inicio VARCHAR(30)  NOT NULL,
  salario         NUMERIC(10,2) NOT NULL,
  salario_desde   TIMESTAMPTZ  NOT NULL,
  atiende_reset   VARCHAR(20)  REFERENCES roles(id)    -- quién atiende su «Restablecer contraseña»
);

CREATE TABLE zonas (
  nombre     VARCHAR(60) PRIMARY KEY,
  costo_min  NUMERIC(12,2) NOT NULL,   -- miles de dólares (intervalo del costo de una sucursal mediana)
  costo_max  NUMERIC(12,2) NOT NULL
);

CREATE TABLE tamanos_sucursal (
  id           VARCHAR(10) PRIMARY KEY CHECK (id IN ('pequena','mediana','grande')),
  nombre       VARCHAR(20) NOT NULL,
  factor_costo NUMERIC(4,2) NOT NULL,
  mesas_min    SMALLINT NOT NULL,
  mesas_max    SMALLINT NOT NULL,
  mesas_base   SMALLINT NOT NULL
);

-- Personal mínimo por tamaño de sucursal
CREATE TABLE plantilla_minima (
  tamano    VARCHAR(10) REFERENCES tamanos_sucursal(id),
  rol_id    VARCHAR(20) REFERENCES roles(id),
  cantidad  SMALLINT NOT NULL CHECK (cantidad >= 0),
  PRIMARY KEY (tamano, rol_id)
);

CREATE TABLE sucursales (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(80)  NOT NULL UNIQUE,
  zona        VARCHAR(60)  NOT NULL REFERENCES zonas(nombre),
  tamano      VARCHAR(10)  NOT NULL REFERENCES tamanos_sucursal(id),
  estado      VARCHAR(20)  NOT NULL DEFAULT 'Operando' CHECK (estado IN ('Operando','Cierre ordenado','Cerrada')),
  mesas       SMALLINT     NOT NULL CHECK (mesas > 0),
  direccion   VARCHAR(160),
  costo       NUMERIC(12,2),
  abierta_en  TIMESTAMPTZ,
  cerrada_en  TIMESTAMPTZ
);

-- Plantilla objetivo de cada sucursal (puede superar el mínimo por tamaño)
CREATE TABLE sucursal_plantilla (
  sucursal_id INTEGER     REFERENCES sucursales(id) ON DELETE CASCADE,
  rol_id      VARCHAR(20) REFERENCES roles(id),
  cantidad    SMALLINT NOT NULL CHECK (cantidad >= 0),
  PRIMARY KEY (sucursal_id, rol_id)
);

CREATE TABLE sucursal_historial (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id INTEGER NOT NULL REFERENCES sucursales(id) ON DELETE CASCADE,
  fecha       TIMESTAMPTZ NOT NULL,
  tipo        VARCHAR(60) NOT NULL,
  detalle     TEXT,
  por         VARCHAR(120)
);

CREATE TABLE usuarios (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario         VARCHAR(40)  NOT NULL UNIQUE,
  nombre          VARCHAR(120) NOT NULL,
  rol_id          VARCHAR(20)  NOT NULL REFERENCES roles(id),
  sucursal_id     INTEGER      REFERENCES sucursales(id),       -- NULL = toda la franquicia
  pass_hash       TEXT         NOT NULL,                        -- bcrypt
  clave_hash      TEXT,                                         -- clave de aprobaciones (gerente / gerente general)
  pin_hash        TEXT,                                         -- PIN de directores
  estado          VARCHAR(20)  NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Despedido','Inhabilitado')),
  documento       VARCHAR(12),                                  -- DUI 00000000-0
  telefono        VARCHAR(9),
  correo          VARCHAR(120),
  foto_url        TEXT,
  ingreso         TIMESTAMPTZ  NOT NULL,
  antig_aplicada  SMALLINT     NOT NULL DEFAULT 0,              -- años de antigüedad ya pagados como aumento
  extra_antiguedad NUMERIC(10,2) NOT NULL DEFAULT 0,
  cambiar_pass    BOOLEAN NOT NULL DEFAULT FALSE,               -- contraseña temporal: solo puede ir a Perfil
  cambiar_pin     BOOLEAN NOT NULL DEFAULT FALSE,
  recup_pass      BOOLEAN NOT NULL DEFAULT FALSE,               -- director entró solo con PIN
  recup_pin       BOOLEAN NOT NULL DEFAULT FALSE,               -- director entró solo con contraseña
  intentos_clave  SMALLINT NOT NULL DEFAULT 0,                  -- 3 intentos fallidos bloquean la clave
  fecha_baja      TIMESTAMPTZ
);
CREATE INDEX usuarios_suc_rol ON usuarios (sucursal_id, rol_id) WHERE estado = 'Activo';

CREATE TABLE usuario_historial (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  fecha       TIMESTAMPTZ NOT NULL,
  tipo        VARCHAR(60) NOT NULL,          -- Contratación, Ascenso, Cambio de rol, Aumento por antigüedad, Despido…
  detalle     TEXT,
  por         VARCHAR(120)
);

-- Turnos: semana NULL = turno base; si no, la semana (lunes) con cambios puntuales
CREATE TABLE turnos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  semana      DATE,
  dias        VARCHAR(12)[] NOT NULL CHECK (array_length(dias, 1) = 7),   -- lun…dom: 'Mañana','Tarde','Noche','7-22' o ''
  UNIQUE NULLS NOT DISTINCT (usuario_id, semana)
);

CREATE TABLE aumentos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  fecha       TIMESTAMPTZ NOT NULL,
  anios       SMALLINT NOT NULL,
  antes       NUMERIC(10,2) NOT NULL,
  despues     NUMERIC(10,2) NOT NULL
);

CREATE TABLE vacantes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id),
  rol_id        VARCHAR(20) NOT NULL REFERENCES roles(id),
  cantidad      SMALLINT NOT NULL CHECK (cantidad > 0),
  cubiertas     SMALLINT NOT NULL DEFAULT 0,
  origen        VARCHAR(60) NOT NULL,            -- Apertura de sucursal, Reemplazo por despido, Cambio de rol, Personal…
  prioridad     VARCHAR(10) NOT NULL CHECK (prioridad IN ('Normal','Alta','Máxima')),
  estado        VARCHAR(12) NOT NULL DEFAULT 'Abierta' CHECK (estado IN ('Abierta','Cubierta','Cancelada')),
  fecha         TIMESTAMPTZ NOT NULL,
  solicitud_id  INTEGER                          -- FK agregada al final (solicitudes)
);

-- =====================================================================
-- 3. Inventario: materias primas, proveedores, lotes
-- =====================================================================

CREATE TABLE mp_unidades (
  nombre        VARCHAR(20) PRIMARY KEY,
  predeterminada BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE mp_categorias (
  nombre        VARCHAR(40) PRIMARY KEY,
  predeterminada BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE materias_primas (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(80) NOT NULL UNIQUE,
  unidad      VARCHAR(20) NOT NULL REFERENCES mp_unidades(nombre),
  categoria   VARCHAR(40) NOT NULL REFERENCES mp_categorias(nombre),
  vida_dias   SMALLINT    NOT NULL DEFAULT 14 CHECK (vida_dias > 0),
  descripcion TEXT        NOT NULL DEFAULT '',
  estado      VARCHAR(15) NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Inhabilitado')),
  foto_url    TEXT
);

CREATE TABLE proveedores (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre               VARCHAR(100) NOT NULL UNIQUE,
  condicion_pago       VARCHAR(10)  NOT NULL CHECK (condicion_pago IN ('Contado','15 días','30 días')),
  estado               VARCHAR(15)  NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Inhabilitado','Eliminado')),
  politica_tipo        VARCHAR(15)  NOT NULL CHECK (politica_tipo IN ('Descuento','Indemnización','Reembolso')),
  politica_tolerancia_h SMALLINT    NOT NULL,     -- horas de tolerancia antes de compensar un retraso
  politica_escala      NUMERIC(8,2) NOT NULL,     -- % o $ por día de retraso
  politica_tope        NUMERIC(8,2) NOT NULL,
  saldo_favor          NUMERIC(12,2) NOT NULL DEFAULT 0,
  foto_url             TEXT,
  creado_por           INTEGER,                   -- FK agregada al final (usuarios); NULL = datos iniciales
  creado               TIMESTAMPTZ,
  editado_por          INTEGER,
  editado              TIMESTAMPTZ
);

-- Altas, ediciones, inhabilitaciones y bajas de cada proveedor
CREATE TABLE proveedor_cambios (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id INTEGER NOT NULL REFERENCES proveedores(id) ON DELETE CASCADE,
  fecha        TIMESTAMPTZ NOT NULL,
  detalle      TEXT NOT NULL
);

-- Catálogo de cada proveedor con su precio base y el de esta semana
CREATE TABLE proveedor_materias (
  proveedor_id   INTEGER REFERENCES proveedores(id) ON DELETE CASCADE,
  mp_id          INTEGER REFERENCES materias_primas(id),
  precio_base    NUMERIC(10,2) NOT NULL CHECK (precio_base > 0),
  precio_actual  NUMERIC(10,2) NOT NULL CHECK (precio_actual > 0),
  PRIMARY KEY (proveedor_id, mp_id)
);

CREATE TABLE proveedor_precios_hist (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id  INTEGER NOT NULL REFERENCES proveedores(id) ON DELETE CASCADE,
  mp_id         INTEGER NOT NULL REFERENCES materias_primas(id),
  precio        NUMERIC(10,2) NOT NULL,
  desde         TIMESTAMPTZ NOT NULL,
  hasta         TIMESTAMPTZ
);

-- Condiciones de entrega por sucursal (si no hay fila, no entrega en esa sucursal)
CREATE TABLE proveedor_sucursales (
  proveedor_id    INTEGER REFERENCES proveedores(id) ON DELETE CASCADE,
  sucursal_id     INTEGER REFERENCES sucursales(id) ON DELETE CASCADE,
  entrega_h       SMALLINT NOT NULL CHECK (entrega_h > 0),
  transporte      NUMERIC(8,2) NOT NULL,
  transporte_min  NUMERIC(8,2) NOT NULL,
  transporte_max  NUMERIC(8,2) NOT NULL,
  PRIMARY KEY (proveedor_id, sucursal_id)
);

CREATE TABLE proveedor_transporte_hist (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id  INTEGER NOT NULL REFERENCES proveedores(id) ON DELETE CASCADE,
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id) ON DELETE CASCADE,
  costo         NUMERIC(8,2) NOT NULL,
  desde         TIMESTAMPTZ NOT NULL,
  hasta         TIMESTAMPTZ
);

CREATE TABLE lotes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku           VARCHAR(30) NOT NULL UNIQUE,
  mp_id         INTEGER NOT NULL REFERENCES materias_primas(id),
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id),
  proveedor_id  INTEGER REFERENCES proveedores(id),
  compra_id     INTEGER,                                  -- FK agregada al final (compras)
  fecha_compra  TIMESTAMPTZ NOT NULL,
  vence         TIMESTAMPTZ NOT NULL,
  cantidad      NUMERIC(12,3) NOT NULL CHECK (cantidad >= 0),
  precio        NUMERIC(10,2) NOT NULL,                   -- costo unitario
  estado        VARCHAR(12) NOT NULL DEFAULT 'Disponible' CHECK (estado IN ('Disponible','Por vencer','Agotado','Vencido')),
  perdido       NUMERIC(12,3) NOT NULL DEFAULT 0,         -- lo que pasó a merma por vencimiento
  avisado       BOOLEAN NOT NULL DEFAULT FALSE            -- ya se avisó a bodega que está por vencer
);
CREATE INDEX lotes_mp_suc ON lotes (mp_id, sucursal_id) WHERE cantidad > 0;

-- Conteo físico de bodega (lo aprueba el gerente con su clave)
CREATE TABLE conteos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id),
  bodega_id     INTEGER NOT NULL REFERENCES usuarios(id),
  fecha         TIMESTAMPTZ NOT NULL,
  estado        VARCHAR(10) NOT NULL DEFAULT 'Enviado' CHECK (estado IN ('Enviado','Aprobado','Rechazado')),
  motivo        TEXT NOT NULL,
  decidio_id    INTEGER REFERENCES usuarios(id),
  decidido      TIMESTAMPTZ,
  motivo_decision TEXT
);

CREATE TABLE conteo_filas (
  conteo_id  INTEGER REFERENCES conteos(id) ON DELETE CASCADE,
  mp_id      INTEGER REFERENCES materias_primas(id),
  sistema    NUMERIC(12,3) NOT NULL,
  contado    NUMERIC(12,3) NOT NULL CHECK (contado >= 0),
  PRIMARY KEY (conteo_id, mp_id)
);

-- Avisos de stock bajo ya enviados (para no repetirlos)
CREATE TABLE avisos_stock (
  sucursal_id INTEGER REFERENCES sucursales(id) ON DELETE CASCADE,
  mp_id       INTEGER REFERENCES materias_primas(id),
  PRIMARY KEY (sucursal_id, mp_id)
);

-- =====================================================================
-- 4. Catálogo de venta: productos, extras, recetas, precios, menú
-- =====================================================================

CREATE TABLE categorias (
  id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(60) NOT NULL UNIQUE,
  icono   VARCHAR(8)                       -- emoji que se muestra si el producto no tiene foto
);

-- Productos del menú y extras (un extra no sale en el menú: se ofrece dentro de productos concretos)
CREATE TABLE productos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT         NOT NULL DEFAULT '',
  precio      NUMERIC(10,2) NOT NULL CHECK (precio >= 0),        -- IVA incluido
  tiempo_min  SMALLINT     NOT NULL CHECK (tiempo_min >= 0),     -- minutos para 1 unidad
  estado      VARCHAR(20)  NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Precio por revisar','Inhabilitado','Eliminado')),
  es_extra    BOOLEAN      NOT NULL DEFAULT FALSE,
  es_reventa  BOOLEAN      NOT NULL DEFAULT FALSE,
  version     SMALLINT     NOT NULL DEFAULT 1,
  foto_url    TEXT,
  creado      TIMESTAMPTZ  NOT NULL,
  publicado   TIMESTAMPTZ                                        -- entró al catálogo (chip «Nuevo»)
);

CREATE TABLE producto_categorias (
  producto_id  INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  categoria_id INTEGER REFERENCES categorias(id),
  PRIMARY KEY (producto_id, categoria_id)
);

-- Receta: materias primas por 1 unidad del producto o extra
CREATE TABLE recetas (
  producto_id  INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  mp_id        INTEGER REFERENCES materias_primas(id),
  cantidad     NUMERIC(10,3) NOT NULL CHECK (cantidad > 0),
  PRIMARY KEY (producto_id, mp_id)
);

-- En qué productos se ofrece cada extra
CREATE TABLE extra_productos (
  extra_id     INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  producto_id  INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  PRIMARY KEY (extra_id, producto_id),
  CHECK (extra_id <> producto_id)
);

-- Versiones anteriores de la receta (cambiar ingredientes crea una versión nueva)
CREATE TABLE producto_versiones (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id  INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  version      SMALLINT NOT NULL,
  receta       JSONB NOT NULL,           -- [{mp_id, cantidad}]
  motivo       TEXT,
  fecha        TIMESTAMPTZ NOT NULL
);

CREATE TABLE precios_historial (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id   INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  precio        NUMERIC(10,2) NOT NULL,
  desde         TIMESTAMPTZ NOT NULL,
  hasta         TIMESTAMPTZ,
  aprobo        VARCHAR(120),
  solicitud_id  INTEGER
);

-- Productos que se venden en cada sucursal
CREATE TABLE sucursal_menu (
  sucursal_id  INTEGER REFERENCES sucursales(id) ON DELETE CASCADE,
  producto_id  INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  PRIMARY KEY (sucursal_id, producto_id)
);

-- Productos cuyo costo alcanzó al precio de venta («Precio por revisar») en una sucursal
CREATE TABLE sucursal_revisar (
  sucursal_id  INTEGER REFERENCES sucursales(id) ON DELETE CASCADE,
  producto_id  INTEGER REFERENCES productos(id) ON DELETE CASCADE,
  PRIMARY KEY (sucursal_id, producto_id)
);

-- =====================================================================
-- 5. Servicio: pedidos, cajas y ventas
-- =====================================================================

CREATE SEQUENCE pedidos_num_seq;

CREATE TABLE pedidos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  num             INTEGER NOT NULL UNIQUE DEFAULT nextval('pedidos_num_seq'),   -- número visible (#124)
  sucursal_id     INTEGER NOT NULL REFERENCES sucursales(id),
  mesero_id       INTEGER NOT NULL REFERENCES usuarios(id),
  cocinero_id     INTEGER REFERENCES usuarios(id),
  tipo            VARCHAR(10) NOT NULL CHECK (tipo IN ('Aquí','Llevar','Delivery')),
  mesa            SMALLINT,
  cliente         VARCHAR(80) NOT NULL DEFAULT '',
  estado          VARCHAR(12) NOT NULL DEFAULT 'Creado'
                  CHECK (estado IN ('Creado','Aceptado','Asignado','Preparando','Listo','Entregado','Cobrado','Cancelado','Rechazado')),
  total           NUMERIC(10,2) NOT NULL DEFAULT 0,
  est_seg         INTEGER NOT NULL,                     -- tiempo estimado (segundos)
  reposicion_de   INTEGER REFERENCES pedidos(id),       -- si es una reposición: pedido original
  consumido       BOOLEAN NOT NULL DEFAULT FALSE,       -- ya se descontaron los insumos
  creado          TIMESTAMPTZ NOT NULL,
  aceptado        TIMESTAMPTZ,
  asignado        TIMESTAMPTZ,
  iniciado        TIMESTAMPTZ,
  terminado       TIMESTAMPTZ,
  entregado       TIMESTAMPTZ,
  cancelado       TIMESTAMPTZ,
  motivo_cancel   TEXT,
  por_demora      BOOLEAN NOT NULL DEFAULT FALSE,
  rechazo_por     INTEGER REFERENCES usuarios(id),
  rechazo_motivo  TEXT,
  rechazo_fecha   TIMESTAMPTZ,
  visto_mesero    BOOLEAN NOT NULL DEFAULT FALSE,       -- el mesero ya vio el rechazo
  visto_cocinero  BOOLEAN NOT NULL DEFAULT FALSE,       -- el cocinero ya vio la cancelación
  salida_pedida   TIMESTAMPTZ,                          -- se le pidió al cliente desocupar la mesa
  mesa_liberada   TIMESTAMPTZ
);
CREATE INDEX pedidos_suc_estado ON pedidos (sucursal_id, estado);
CREATE INDEX pedidos_mesero ON pedidos (mesero_id, creado DESC);
CREATE INDEX pedidos_cocinero ON pedidos (cocinero_id) WHERE cocinero_id IS NOT NULL;

CREATE TABLE pedido_lineas (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id    INTEGER NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  orden        SMALLINT NOT NULL,
  producto_id  INTEGER NOT NULL REFERENCES productos(id),
  nombre       VARCHAR(100) NOT NULL,                    -- copia del nombre al momento de vender
  cantidad     SMALLINT NOT NULL CHECK (cantidad > 0),
  precio_unit  NUMERIC(10,2) NOT NULL,                   -- precio con oferta + extras, IVA incluido
  UNIQUE (pedido_id, orden)
);

CREATE TABLE pedido_linea_extras (
  linea_id   INTEGER REFERENCES pedido_lineas(id) ON DELETE CASCADE,
  extra_id   INTEGER REFERENCES productos(id),
  nombre     VARCHAR(100) NOT NULL,
  precio     NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (linea_id, extra_id)
);

-- Insumos reservados por el pedido (se descuentan de los lotes al iniciar la preparación)
CREATE TABLE pedido_reservas (
  pedido_id  INTEGER REFERENCES pedidos(id) ON DELETE CASCADE,
  mp_id      INTEGER REFERENCES materias_primas(id),
  cantidad   NUMERIC(12,3) NOT NULL,
  PRIMARY KEY (pedido_id, mp_id)
);

CREATE TABLE cajas (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id),
  mesero_id     INTEGER NOT NULL REFERENCES usuarios(id),
  fondo         NUMERIC(10,2) NOT NULL CHECK (fondo >= 0),
  estado        VARCHAR(25) NOT NULL DEFAULT 'Abierta'
                CHECK (estado IN ('Abierta','Pendiente de aprobación','Aprobada','Observada','Rechazada')),
  abierta       TIMESTAMPTZ NOT NULL,
  cerrada       TIMESTAMPTZ,
  declarado     NUMERIC(10,2),                -- efectivo contado por el mesero
  esp_efectivo  NUMERIC(10,2),                -- esperado al cerrar
  esp_tarjeta   NUMERIC(10,2),
  esp_bitcoin   NUMERIC(10,2),
  comentario    TEXT NOT NULL DEFAULT '',     -- comentario del gerente
  decidio_id    INTEGER REFERENCES usuarios(id),
  decidida      TIMESTAMPTZ
);
CREATE UNIQUE INDEX cajas_una_abierta ON cajas (mesero_id) WHERE estado = 'Abierta';

CREATE TABLE ventas (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id   INTEGER NOT NULL REFERENCES sucursales(id),
  pedido_id     INTEGER NOT NULL UNIQUE REFERENCES pedidos(id),
  mesero_id     INTEGER NOT NULL REFERENCES usuarios(id),
  caja_id       INTEGER REFERENCES cajas(id),
  fecha         TIMESTAMPTZ NOT NULL,
  metodo        VARCHAR(10) NOT NULL CHECK (metodo IN ('Efectivo','Tarjeta','Bitcoin')),
  referencia    TEXT NOT NULL DEFAULT '',
  pago          JSONB NOT NULL DEFAULT '{}',  -- datos del método (recibido/cambio, tarjeta, bitcoin)
