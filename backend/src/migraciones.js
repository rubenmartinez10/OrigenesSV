  // cancelar un pedido ya iniciado en cocina: el cliente paga los insumos usados
  'ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS cargo_cancel NUMERIC(10,2) NOT NULL DEFAULT 0',
