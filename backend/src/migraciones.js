import { q } from './db.js';

/*
 * Cambios de esquema idempotentes que se aplican al arrancar, para que una base de datos
 * creada con una versión anterior quede igual a database/init/01_schema.sql sin perder datos.
 * Todo lo que se agregue aquí también está en 01_schema.sql (instalaciones nuevas).
 */
const PASOS = [
  // reloj que se pausa cuando nadie usa la app
  'ALTER TABLE sistema ADD COLUMN IF NOT EXISTS pausado BOOLEAN NOT NULL DEFAULT FALSE',
  `CREATE OR REPLACE FUNCTION ahora() RETURNS TIMESTAMPTZ LANGUAGE sql STABLE AS $$
     SELECT CASE WHEN pausado THEN reloj_base ELSE reloj_base + (now() - real_base) END FROM sistema WHERE id = 1
   $$`,
  // una materia prima puede tener varias categorías
  `CREATE TABLE IF NOT EXISTS materia_categorias (
     mp_id     INTEGER REFERENCES materias_primas(id) ON DELETE CASCADE,
     categoria VARCHAR(40) REFERENCES mp_categorias(nombre),
     PRIMARY KEY (mp_id, categoria))`,
  `INSERT INTO materia_categorias (mp_id, categoria) SELECT id, categoria FROM materias_primas ON CONFLICT DO NOTHING`,
  // materias primas inhabilitadas en una sucursal (las aprueba el gerente)
  `CREATE TABLE IF NOT EXISTS sucursal_mp_inhabilitada (
     sucursal_id INTEGER REFERENCES sucursales(id) ON DELETE CASCADE,
     mp_id       INTEGER REFERENCES materias_primas(id),
     fecha       TIMESTAMPTZ NOT NULL,
     solicitud_id INTEGER REFERENCES solicitudes(id),
     PRIMARY KEY (sucursal_id, mp_id))`,
  // altas y bajas de productos en el menú de cada sucursal
  `CREATE TABLE IF NOT EXISTS menu_historial (
     id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     sucursal_id INTEGER NOT NULL REFERENCES sucursales(id) ON DELETE CASCADE,
     producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
     estado      VARCHAR(20) NOT NULL CHECK (estado IN ('Activo','Inhabilitado')),
     fecha       TIMESTAMPTZ NOT NULL,
     razon       TEXT NOT NULL DEFAULT '',
     por         VARCHAR(120))`,
  'ALTER TABLE productos ADD COLUMN IF NOT EXISTS publicado TIMESTAMPTZ',
  'ALTER TABLE ofertas ADD COLUMN IF NOT EXISTS desde TIMESTAMPTZ',
  // facturas: anuladas (devolución o cancelación sin costo), archivo de RR. HH. y pago con saldo a favor
  'ALTER TABLE facturas DROP CONSTRAINT IF EXISTS facturas_estado_check',
  `ALTER TABLE facturas ADD CONSTRAINT facturas_estado_check CHECK (estado IN ('Pendiente','Pagada','Anulada'))`,
  'ALTER TABLE facturas ADD COLUMN IF NOT EXISTS archivada_por INTEGER REFERENCES usuarios(id)',
  'ALTER TABLE facturas ADD COLUMN IF NOT EXISTS pagado_monto NUMERIC(12,2)',
  'ALTER TABLE facturas ADD COLUMN IF NOT EXISTS saldo_usado NUMERIC(12,2) NOT NULL DEFAULT 0',
  // proveedores: eliminados (solo director), quién los registró y su historial de cambios
  'ALTER TABLE proveedores DROP CONSTRAINT IF EXISTS proveedores_estado_check',
  `ALTER TABLE proveedores ADD CONSTRAINT proveedores_estado_check CHECK (estado IN ('Activo','Inhabilitado','Eliminado'))`,
  'ALTER TABLE proveedores ADD COLUMN IF NOT EXISTS creado_por INTEGER REFERENCES usuarios(id)',
  'ALTER TABLE proveedores ADD COLUMN IF NOT EXISTS creado TIMESTAMPTZ',
  'ALTER TABLE proveedores ADD COLUMN IF NOT EXISTS editado_por INTEGER REFERENCES usuarios(id)',
  'ALTER TABLE proveedores ADD COLUMN IF NOT EXISTS editado TIMESTAMPTZ',
  `CREATE TABLE IF NOT EXISTS proveedor_cambios (
     id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     proveedor_id INTEGER NOT NULL REFERENCES proveedores(id) ON DELETE CASCADE,
     fecha        TIMESTAMPTZ NOT NULL,
     detalle      TEXT NOT NULL)`,
  // nómina: base para renta de cada pago y fecha de envío del reporte
  'ALTER TABLE planilla_filas ADD COLUMN IF NOT EXISTS base NUMERIC(10,2) NOT NULL DEFAULT 0',
  'ALTER TABLE reportes_pago ADD COLUMN IF NOT EXISTS enviado TIMESTAMPTZ',
];

export async function migrar() {
  for (const sql of PASOS) await q(sql);
}
